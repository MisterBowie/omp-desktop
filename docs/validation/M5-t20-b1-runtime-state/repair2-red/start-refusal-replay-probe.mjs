import { register } from 'node:module';
import { pathToFileURL } from 'node:url';
import { writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
const repo='/Users/vv/Documents/对话/omp-desktop-review-m5-r4b';
register(pathToFileURL(repo+'/app/apps/desktop/test/helpers/ts-import-hooks.mjs'));
const { OmpSessionRunner }=await import(pathToFileURL(repo+'/app/packages/omp-runtime/src/session/runner.ts'));
const { encodeStartRefusal, OMP_START_REFUSAL_KIND, OMP_START_REFUSAL_VERSION }=await import(pathToFileURL(repo+'/app/packages/omp-runtime/src/session/start-refusal.ts'));
const frames=new Set(), failures=new Set(), envelopes=[], ends=[];
const runtime={pid:1234,usable:true,write:()=>true,request:async()=>({success:true}),onFrame:handler=>{frames.add(handler);return()=>frames.delete(handler);},onFailure:handler=>{failures.add(handler);return()=>failures.delete(handler);}};
let time=100;
const runner=new OmpSessionRunner({sessionId:'desktop-parent',runtime,emit:e=>envelopes.push(e),onTurnEnd:e=>ends.push(e),nativeSessionIdentity:()=> 'native-parent',now:()=>time});
const oldNotice={type:'extension_ui_request',id:'old-notice',method:'notify',notifyType:'error',message:encodeStartRefusal({v:OMP_START_REFUSAL_VERSION,kind:OMP_START_REFUSAL_KIND,sessionId:'native-parent',code:'state-invalid',reason:'old generation state invalid',refusalId:'old-refusal-id',at:time})};
const send=frame=>{for(const handler of frames)handler(frame);};
const first=await runner.prompt('first turn');
send(oldNotice);
const firstState=runner.runState(),firstEnds=[...ends];
time=200;
const second=await runner.prompt('second turn awaiting agent_start');
const beforeReplayState=runner.runState();
send(oldNotice);
const afterReplayState=runner.runState();
const report={desktopCommit:execFileSync('git',['rev-parse','HEAD'],{cwd:repo,encoding:'utf8'}).trim(),layer:'production runner with scripted formal RPC frames; no runtime process/provider',first,firstState,firstEnds,second,beforeReplayState,afterReplayState,replayedNoticeClosedNewGeneration:beforeReplayState==='running'&&afterReplayState==='idle',terminalErrors:envelopes.filter(e=>e.event.type==='error'),ends:[...ends],diagnostics:runner.diagnostics()};
runner.dispose('replay probe complete');
writeFileSync('/Users/vv/Documents/对话/omp-t20-b1-review-20261002/start-refusal-replay-'+report.desktopCommit.slice(0,8)+'.json',JSON.stringify(report,null,2)+'\n');
